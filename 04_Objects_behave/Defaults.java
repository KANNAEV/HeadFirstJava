public class Defaults {
    public static void main(String[] args) {
        int x = 0;
        System.out.println("Значение по умолчанию для int: " + x);

        double d = 0.0;
        System.out.println("Значение по умолчанию для double: " + d);

        boolean b = false;
        System.out.println("Значение по умолчанию для boolean: " + b);

        char c = '\u0000';
        System.out.println("Значение по умолчанию для char: '" + c + "'");

        String s = null;
        System.out.println("Значение по умолчанию для String: " + s);
    }

}
